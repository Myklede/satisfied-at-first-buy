// Builds the motion-bake WebAssembly kernels: solver.as.ts (AssemblyScript) -> solverWasm.ts,
// the binary embedded as base64 so the kiosk loads it offline, in the worker and in Node alike.
//   node apps/web/src/engine/cloth/wasm/build.mjs          rebuild solverWasm.ts
//   node apps/web/src/engine/cloth/wasm/build.mjs --check  exit 1 unless solverWasm.ts is the
//                                                          build of the current source
// The compiler is the pinned `assemblyscript` devDependency (package-lock.json); nothing is
// fetched. Flags: -O3, no assertions, stub runtime (the kernels never allocate), default
// features only (no SIMD, so no relaxed FMA): see solver.as.ts for the bit-identity rules.
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import asc from 'assemblyscript/asc';
import * as prettier from 'prettier';

const HERE = new URL('./', import.meta.url);
const SOURCE = new URL('solver.as.ts', HERE);
const OUTPUT = new URL('solverWasm.ts', HERE);
export const FLAGS = { optimizeLevel: 3, shrinkLevel: 0, noAssert: true, runtime: 'stub' };

/** Compiles the current source; returns the generated module text and the binary. */
export async function buildSolverWasm() {
  const source = await readFile(SOURCE, 'utf8');
  const result = await asc.compileString({ 'solver.as.ts': source }, FLAGS);
  if (result.error || !result.binary)
    throw new Error(`asc failed: ${result.error?.message}\n${result.stderr.toString()}`);
  const binary = result.binary;
  const sha = (data) => createHash('sha256').update(data).digest('hex');
  const base64 = Buffer.from(binary).toString('base64');
  const lines = base64.match(/.{1,96}/g) ?? [];
  const text = [
    '// Generated by build.mjs from solver.as.ts: do not edit (npm run build:wasm).',
    `// assemblyscript ${asc.version}, ${JSON.stringify(FLAGS)}.`,
    `export const SOLVER_WASM_SOURCE_SHA256 = '${sha(source)}';`,
    `export const SOLVER_WASM_SHA256 = '${sha(binary)}';`,
    'export const SOLVER_WASM_BASE64 =',
    ...lines.map((line, i) => `  '${line}'${i === lines.length - 1 ? ';' : ' +'}`),
    '',
  ].join('\n');
  // Formatted like the rest of the repo, so `npm run lint` (prettier --check) passes as well.
  const filepath = fileURLToPath(OUTPUT),
    options = (await prettier.resolveConfig(filepath)) ?? {};
  return { text: await prettier.format(text, { ...options, filepath }), binary };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { text, binary } = await buildSolverWasm();
  if (process.argv.includes('--check')) {
    const committed = await readFile(OUTPUT, 'utf8').catch(() => '');
    if (committed !== text) {
      console.error('solverWasm.ts is not the build of solver.as.ts: run npm run build:wasm');
      process.exit(1);
    }
    console.log(`solverWasm.ts matches solver.as.ts (${binary.length} bytes)`);
  } else {
    await writeFile(OUTPUT, text);
    console.log(`wrote solverWasm.ts (${binary.length} bytes)`);
  }
}
